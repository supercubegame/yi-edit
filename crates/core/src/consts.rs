//! 全项目共享的常量。
//!
//! 这一组是**相互耦合**的，改一个必须重算另一个。下面每条关系在
//! crates/meta/tests/coupling.rs 里都有一条等号断言钉着 —— 因为写在散文里的
//! 「改一个必须重算另一个」自己会腐化：前提变了而数字留在原地。
//!
//! - `CHUNK_OVERLAP == MAX_PATTERN_LEN - 1`
//!   流式搜索/替换在块边界上要保留的重叠字节数。少一个字节，横跨边界的匹配就会静默丢失。
//! - `HUGE_FILE_THRESHOLD % CHUNK_SIZE == 0`
//!   大文件阈值必须是块大小的整数倍，否则最后一块的长度会成为一个只在特定文件尺寸下出现的边界。
//! - `CHUNK_SIZE >= CHUNK_OVERLAP * 16`
//!   重叠相对块要足够小，否则每块的有效吞吐被重叠吃掉。

/// 超过这个大小的文件走内存映射 + 虚拟滚动，不整读进内存。
pub const HUGE_FILE_THRESHOLD: u64 = 64 * 1024 * 1024;

/// 流式读写的块大小。
pub const CHUNK_SIZE: usize = 4 * 1024 * 1024;

/// 流式替换支持的最长模式。超过就直接报错，而不是悄悄截断。
pub const MAX_PATTERN_LEN: usize = 1024;

/// 块之间保留的重叠字节数。
/// M2：变异体——去掉了 -1。耦合等号断言应该抓住它。
pub const CHUNK_OVERLAP: usize = MAX_PATTERN_LEN;

/// 撤销栈上限。到顶之后丢最旧的一条（不是拒绝新编辑）。
/// 注意：任何依赖「撤销到底能回到原文」的测试，夹具的操作数必须小于这个值，
/// 否则那个测试测的是「丢弃策略」而不是「撤销正确性」，而两者失败时长得一样。
pub const MAX_UNDO: usize = 4096;
